def examples_block(examples, limit=12):
    """Ручные правки владельца — как примеры прямо в промпте.

    Промпт не объяснит модели, что «ЦИТ» — это партнёр-интегратор, а не
    заказчик: такое знание есть только у владельца. Зато один раз
    исправленный контакт учит и остальных из той же компании.
    """
    # Порядок примеров модель чувствует, поэтому оставляем как есть, но не
    # даём одной категории занять весь список: иначе она мерещится везде.
    per_kind = max(4, limit // len(KINDS))
    taken = {}
    lines = []
    for title, kind in examples:
        title = ' '.join(str(title or '').split())[:40]
        if not title or not kind or taken.get(kind, 0) >= per_kind:
            continue
        taken[kind] = taken.get(kind, 0) + 1
        lines.append('- {} -> {}'.format(title, kind))
        if len(lines) >= limit:
            break
    if not lines:
        return ''
    return ('\nВладелец аккаунта уже размечал контакты руками. Это эталон, '
            'ориентируйся на него, особенно если узнаёшь ту же компанию:\n'
            + '\n'.join(lines) + '\n')


