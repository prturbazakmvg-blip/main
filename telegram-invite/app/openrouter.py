    data = parse_json(answer)

    opening = clean_opening(str(data.get('opening', '')))
    body = str(data.get('body', '')).strip()
    notes = str(data.get('notes', ''))[:60]

    base_anchors = anchors(base_text)
    if base_anchors - anchors(body):
        # модель порезала факты — берём заготовку как есть
        body = base_text.strip()
        notes = (notes + '; тело вернул без изменений').strip('; ')

    if not opening:
        return body, notes or 'без изменений'

    # своё приветствие уже есть — второе в теле лишнее
    trimmed = strip_greeting(body)
    if trimmed and not (base_anchors - anchors(trimmed)):
        body = trimmed

    return '{}\n\n{}'.format(opening, body), notes
