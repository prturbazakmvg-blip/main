def _clean_name(name):
    """Имя должно быть кириллицей и без мусора вроде «[Alto]»."""
    text = (name or '').strip().strip('.,!?"\'«»')
    if not text or len(text) > 24:
        return ''
    if any(ch in text for ch in '[]()@0123456789'):
        return ''
    letters = [ch for ch in text if ch.isalpha()]
    if not letters:
        return ''
    first = text.split()[0]
    letters = [ch for ch in first if ch.isalpha()]
    cyrillic = sum(1 for ch in letters if 'а' <= ch.lower() <= 'я' or ch.lower() == 'ё')
    if cyrillic < len(letters):      # латиницу переводим, «Maxim» -> «Максим»
        return names.to_cyrillic(first)
    return first.capitalize()


def parse(answer):
    """Ответ ждём в JSON, но подстрахуемся: модели любят обернуть его
    в ```json или просто написать слово."""
    text = (answer or '').strip()
    if '```' in text:
        text = text.split('```')[1]
        text = text[4:] if text.lower().startswith('json') else text
    try:
        data = json.loads(text.strip())
        if isinstance(data, dict):
            return normalize(str(data.get('type', ''))), str(data.get('why', ''))[:60]
    except (ValueError, TypeError):
        pass
    return normalize(text), ''


def normalize(answer):
    """Модель иногда добавляет точку или кавычки — приводим к нашему списку."""
    text = (answer or '').strip().lower().strip('.,"«»\' \n')
    for kind in KINDS:
        if kind in text:
            return kind
    for old, new in RENAMED.items():
        if old in text:
            return new
    if 'коллег' in text or 'подчинён' in text:
        return 'коллеги'
    if 'кандидат' in text or 'соискат' in text or 'резюме' in text:
        return 'соискатель'
    if 'подряд' in text or 'фрилансер' in text or 'аутстафф' in text:
        return 'подрядчик'
    if 'агентств' in text or 'студи' in text or 'it' in text or 'ит' in text:
        return 'ит и digital'
    return 'другое'


def check_key(api_key, timeout=20):
    """Быстрая проверка ключа: список моделей доступен и без него, поэтому
    дёргаем эндпоинт, который требует авторизации."""
    request = Request(
        'https://openrouter.ai/api/v1/key',
        headers={'Authorization': 'Bearer {}'.format(api_key)},
    )
    try:
        with urlopen(request, timeout=timeout) as response:
            data = json.loads(response.read().decode('utf-8'))
    except HTTPError as e:
        raise OpenRouterError('ключ не принят ({})'.format(e.code))
    except URLError as e:
        raise OpenRouterError('нет связи с OpenRouter: {}'.format(e.reason))
    return data.get('data', {})


