# Общие слова, которые сами по себе должность, но с уточнением — уже другая:
# «креативный директор» это не «директор», и упрощать до него нельзя.
GENERIC_ROLES = ('директор', 'менеджер', 'специалист', 'руководитель',
                 'консультант', 'начальник')

# Слова, которые ничего не уточняют: «директор компании» — тот же директор
ROLE_NOISE = ('компании', 'фирмы', 'организации', 'отдела', 'департамента',
              'по', 'в', 'и', 'the', 'of')

# Мусор, который модель охотно пишет в поле компании
NOT_A_COMPANY = ('неизвестн', 'не указан', 'нет данных', 'отсутств', 'н/д',
                 'unknown', 'фрилансер', 'самозанят', 'частное лицо', 'нет')

# Из названия компании это можно убрать без потери смысла
COMPANY_NOISE = ('ооо', 'зао', 'оао', 'ип', 'ltd', 'llc', 'inc', 'гк',
                 'компания', 'агентство', 'студия', 'группа компаний')


def known_role(text):
    """Узнали должность? Тогда её типовое название, иначе пусто.

    Отдельно от normalize_role: тот возвращает и незнакомый текст, поэтому
    для проверки «это вообще должность?» не годится — «finch» он тоже
    вернул бы, и компания уехала бы в должности.
    """
    lowered = ' '.join((text or '').lower().split())
    if not lowered or any(bad in lowered for bad in NOT_A_COMPANY):
        return ''
    for variants, canonical in ROLES:
        if any(variant in lowered for variant in variants):
            return canonical
    # «директор» без уточнений — просто директор, а «креативный директор»
    # оставляем целиком: уточнение здесь и есть должность
    words = [w for w in lowered.replace('-', ' ').replace(',', ' ').split()
             if w not in ROLE_NOISE]
    if len(words) == 1 and words[0] in GENERIC_ROLES:
        return words[0]
    return ''


def normalize_role(text):
    """Должность к одному из типовых названий. Не узнали — оставляем как есть."""
    lowered = ' '.join((text or '').lower().split())
    if not lowered or any(bad in lowered for bad in NOT_A_COMPANY):
        return ''
    canonical = known_role(text)
    if canonical:
        return canonical

    # незнакомую должность оставляем как есть, но только если это похоже на
    # слова: в профилях попадаются позывные и коды вроде «R8AEC»
    if any(ch.isdigit() for ch in lowered) or len(lowered) < 3:
        return ''
    if not any(ch in lowered for ch in 'аеёиоуыэюяaeiou'):
        return ''
    return ' '.join((text or '').split())[:24]


def normalize_company(text):
    """Название компании без «ООО» и без должностей.

    Модель постоянно пишет в компанию то, что на самом деле роль:
    «разработчик», «фрилансер», «маркетолог». Такое отбрасываем — иначе в
    таблице «компания: дизайнер».
    """
    cleaned = ' '.join((text or '').split()).strip('«»"\'.,')
    if not cleaned:
        return ''
    lowered = cleaned.lower()
    if any(bad in lowered for bad in NOT_A_COMPANY):
        return ''
    words = [w for w in cleaned.split() if w.lower().strip('.,') not in COMPANY_NOISE]
    cleaned = ' '.join(words).strip('«»"\'.,')
    if not cleaned:
        return ''
    # осталась одна только должность — это не компания
    if known_role(cleaned) and not any(ch.isdigit() for ch in cleaned):
        return ''
    return cleaned[:32]


# Компания в заголовке чата: «Иван[Alto]», «Никита [метран]»,
# «Дмитрий Щипачев finch»
BRACKETED = re.compile(r'[\[(]\s*([^\])]{2,32}?)\s*[\])]')


def looks_like_role(text):
    """Похоже на должность, пусть и с уточнением: «руководитель екома»."""
    if known_role(text):
        return True
    words = ' '.join((text or '').lower().split()).replace('-', ' ').split()
    return any(word in GENERIC_ROLES for word in words)


def title_company(title):
    """Название компании прямо из имени контакта.

    Модель такое пропускает: в переписке компании нет, в описании профиля
    тоже, а в имени она дописана — скобками или просто в конце строчными.
    """
    text = ' '.join((title or '').split())
    for chunk in BRACKETED.findall(text):
        if looks_like_role(chunk):       # «[дизайнер]» — должность, не компания
            continue
        found = normalize_company(chunk)
        if found:
            return found

    words = BRACKETED.sub(' ', text).split()
    if len(words) < 2:
        return ''
    last = words[-1].strip('.,!?:;«»"\'')
    # только строчное слово или домен: фамилию с большой буквы за компанию
    # принимать нельзя — «Дмитрий Тарасов» это не компания «Тарасов»
    if len(last) < 3 or looks_like_role(last):
        return ''
    if last.islower() or '.' in last:
        return normalize_company(last)
    return ''


