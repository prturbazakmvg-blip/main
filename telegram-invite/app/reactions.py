# Слова, по которым узнаём разговор именно про эту конференцию. Общие
# («конференция», «митап») притаскивают чужие мероприятия.
EVENT_WORDS = ('agday', 'agdays', 'ai growth day', 'ai growth days',
               'growth days', 'агдейс', 'агдэйс')


def about_event(text, extra=()):
    lowered = (text or '').lower()
    return any(word in lowered for word in tuple(EVENT_WORDS) + tuple(extra))


def classify(text):
    """Вид реакции или '' — если ответ ни о чём не говорит."""
    lowered = ' '.join((text or '').lower().split())
    if not lowered:
        return ''
    # Анонсы, черновики постов и ответы ботов — не реакция человека. Узнаются
    # по разметке и по пачке ссылок: живые ответы в переписке так не пишут.
    if '**' in lowered or lowered.count('http') > 1:
        return ''
    for kind in KINDS:
        if any(mark in lowered for mark in MARKS[kind]):
            return kind
    return ''


def _reply_lines(transcript, extra=()):
    """Ответы собеседника, шедшие сразу за нашим упоминанием конференции."""
    found = []
    lines = [line for line in (transcript or '').splitlines() if line.strip()]
    for index, line in enumerate(lines):
        if not line.startswith('я:') or not about_event(line, extra):
            continue
        for nxt in lines[index + 1:index + 4]:
            if nxt.startswith('я:'):
                break
            found.append(re.sub(r'^он:\s*', '', nxt))
    return found


def from_transcript(transcript, extra=()):
    """Вид реакции по личной переписке.

    extra — приметы конференции из самого текста приглашения. Зашитый
    список знает только про AGDays: у коллеги мероприятие своё.
    """
    return best(classify(line) for line in _reply_lines(transcript, extra))


def from_talk(entries):
    """Вид реакции по репликам человека в группах.

    entries — список строк: что он писал про конференцию не в личке.
    """
    return best(classify(text) for text in entries or ())


def best(kinds):
    """Самая говорящая из найденных реакций."""
    found = {kind for kind in kinds if kind}
    for kind in KINDS:
        if kind in found:
            return kind
    return ''


def note(kind, address='вы', sex=''):
    """Фраза-оговорка или '' — если по этому виду сказать нечего.

    sex — «м», «ж» или '' — нужен только для «ты»: в прошедшем времени
    без рода не обойтись, а «Ульяна, ты передавал» — заметная ошибка.
    """
    found = NOTES.get(kind, {}).get(address, '')
    if isinstance(found, dict):
        return found.get(sex, found.get('', ''))
    return found
